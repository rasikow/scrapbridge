function hoursFromNow(h) {
  return new Date(Date.now() + h * 3600000).toISOString()
}
function hoursAgo(h) {
  return new Date(Date.now() - h * 3600000).toISOString()
}
function minutesFromNow(m) {
  return new Date(Date.now() + m * 60000).toISOString()
}

function image(materialId, grade, seedIndex) {
  const material = getMaterial(materialId) || {}
  if (material.photo) {
    return { name: `${materialId}.jpg`, sizeKb: 15, uploadedAt: new Date().toISOString(), dataUrl: material.photo }
  }
  const dataUrl = generateProductArtwork(material, grade)
  return { name: `${materialId}-auction-${seedIndex}.jpg`, sizeKb: Math.round((dataUrl.length * 0.75) / 1024), uploadedAt: new Date().toISOString(), dataUrl }
}

